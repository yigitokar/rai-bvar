def posterior_cases() -> list[dict[str, Any]]:
    return load("r_bvar_posterior.json")["cases"]


@pytest.mark.parametrize(
    ("case_id", "index"),
    glp_entries(posterior_cases()),
    ids=[
        entry_id(
            case_by_id("r_bvar_posterior.json", c),
            case_by_id("r_bvar_posterior.json", c)["grid"][i],
        )
        for c, i in glp_entries(posterior_cases())
    ],
)
def test_posterior_moments_fixed_hyperparameters(rb, case_id, index):
    case = case_by_id("r_bvar_posterior.json", case_id)
    entry = case["grid"][index]
    fit = fixed_fit("r_bvar_posterior.json", case_id, entry["lambda"], entry["soc"], entry["sur"])
    post = fit.posterior()
    n = case["M"]
    assert post.mean.shape == (case["K"], n)
    assert post.df == pytest.approx(entry["df"], abs=0)
    assert scaled_max_diff(post.mean, entry["mean"]) < RTOL_MOMENTS
    assert scaled_max_diff(post.scale, entry["scale"]) < RTOL_MOMENTS
    sigma_mean = np.asarray(post.scale) / (post.df - n - 1)
    assert scaled_max_diff(sigma_mean, entry["sigma_mean"]) < RTOL_MOMENTS
    omega, ref = np.asarray(post.omega()), np.asarray(entry["omega"])
    np.testing.assert_allclose(np.diag(omega), np.diag(ref), rtol=RTOL_MOMENTS)
    scale = 1.0 / np.sqrt(np.diag(ref))
    np.testing.assert_allclose(
        omega * np.outer(scale, scale), ref * np.outer(scale, scale), rtol=0, atol=RTOL_MOMENTS
    )
    # BVAR's own (normal-equation) numbers, to their documented accuracy.
    assert (
        scaled_max_diff(post.mean, entry["mean_bvar"])
        < RTOL_MOMENTS + 2 * entry["bvar_vs_exact"]["mean"]
    )
    assert (
        scaled_max_diff(post.scale, entry["scale_bvar"])
        < RTOL_MOMENTS + 2 * entry["bvar_vs_exact"]["scale"]
    )


