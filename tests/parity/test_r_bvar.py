"""Parity with the R package ``BVAR`` 1.0.5 (Kuschnig & Vashold), SPEC §10.4.

The fixtures ``tests/parity/fixtures/r_bvar_*.json`` are generated by ``tools/make_r_fixtures.R``
(not run in CI; R is not needed here). Every convention behind the numbers, and every place
where BVAR deviates from GLP (2015), is documented in ``tests/parity/BVAR_PARAMETRIZATION.md``.
In short, the fixtures fix ψ explicitly (IW scale diagonal, variance units), use the GLP
initial-observation mean ``ȳ0 = mean(y_1..y_p)`` for the SOC/SUR dummies, and compare against
the *exact* conjugate formulas wherever BVAR is inexact (dummy-only marginal likelihood with a
non-random-walk prior mean, normal-equation round-off, forecast noise scaled by Σ).

Tests that need the analytic engine skip cleanly while ``rai_bvar.BVAR`` is not importable; the
fixture-integrity tests at the top run regardless.
"""

from __future__ import annotations

import hashlib
import json
from functools import cache
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd
import pytest
from scipy.linalg import solve_triangular
from scipy.special import gammaln

FIXTURES = Path(__file__).parent / "fixtures"

# Tolerances (justified in BVAR_PARAMETRIZATION.md §12).
RTOL_LOG_ML = 1e-8  # log p(Y | h) at fixed h; BVAR and the exact values agree to ~1e-11
RTOL_MOMENTS = 1e-8  # NIW posterior parameters, relative to the largest entry of each matrix
RTOL_MODE = 1e-3  # posterior mode of the hyperparameters
MC_Z = 4.0  # Monte Carlo comparisons: |ours − R| ≤ MC_Z · sqrt(mcse_R² + mcse_ours²)

MH_DRAWS, MH_BURN, MH_CHAINS = 5000, 1000, 4  # rai-bvar chain length for the MH parity runs
MH_SAMPLES = 20000  # parameter / forecast draws taken from the MH fit (= chains x draws)
IID_FORECAST_DRAWS = 50000  # forecast draws at fixed hyperparameters (iid posterior draws)


