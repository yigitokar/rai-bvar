@pytest.fixture(scope="module")
def rb():
    try:
        import rai_bvar

        for name in ("BVAR", "Minnesota", "Linear", "Constant", "GLPHyperpriors", "GammaPrior"):
            getattr(rai_bvar, name)
    except (ImportError, AttributeError) as exc:  # pragma: no cover - depends on the engine
        pytest.skip(f"rai_bvar.BVAR (analytic engine) is not importable yet: {exc}")
    return rai_bvar


def hyperpriors_from(spec: dict[str, Any]):
    import rai_bvar as rb

    hp = spec.get("hyperpriors") or load("r_bvar_logml.json")["hyperpriors"]
    fields = {"lambda": "lambda_", "soc": "soc", "sur": "sur"}
    kwargs = {
        fields[name]: rb.GammaPrior(mode=h["mode"], sd=h["sd"], lower=h["lower"], upper=h["upper"])
        for name, h in hp.items()
    }
    return rb.GLPHyperpriors(**kwargs)


def build_model(
    spec: dict[str, Any],
    *,
    lambda_: float,
    soc: float | None,
    sur: float | None,
    hierarchy: str = "fixed",
    hyper: str | tuple[str, ...] = "auto",
    psi: Any = None,
    mh_seed: int | None = None,
):
    import rai_bvar as rb

    kwargs: dict[str, Any] = {
        "lambda_": float(lambda_),
        "alpha": float(spec["alpha"]),
        "psi": tuple(spec["psi"]) if psi is None else psi,
        "soc": soc,
        "sur": sur,
        "soc_scope": "all",  # R BVAR builds SOC rows for every variable (GLP)
        "mean": float(spec["mean"]),
        "var_const": float(spec["var_const"]),
        "hierarchy": hierarchy,
        "hyper": hyper,
        "hyperpriors": hyperpriors_from(spec),
    }
    if mh_seed is not None and hasattr(rb, "MHSettings"):
        kwargs["mh"] = rb.MHSettings(draws=MH_DRAWS, burn=MH_BURN, chains=MH_CHAINS, seed=mh_seed)
    prior = rb.Minnesota(**kwargs)
    return rb.BVAR(
        mean=rb.Linear(prior=prior),
        vol=rb.Constant(prior="iw"),
        lags=int(spec["lags"]),
        deterministic="c",
    )


@cache
def fixed_fit(file: str, case_id: str, lambda_: float, soc: float | None, sur: float | None):
    spec = case_by_id(file, case_id)
    model = build_model(spec, lambda_=lambda_, soc=soc, sur=sur, hierarchy="fixed")
    return model.fit(var_data(spec["dataset"]))


@cache
def eb_fit(run_id: str):
    run = next(r for r in load("r_bvar_eb.json")["runs"] if r["id"] == run_id)
    model = build_model(
        run,
        lambda_=run["hyperpriors"]["lambda"]["mode"],
        soc=run.get("soc"),
        sur=run.get("sur"),
        hierarchy="eb",
        hyper=tuple(run["hyper"]),
    )
    return run, model.fit(var_data(run["dataset"]))


@cache
def mh_fit(run_id: str):
    run = next(r for r in load("r_bvar_mh.json")["runs"] if r["id"] == run_id)
    model = build_model(
        run,
        lambda_=run["hyperpriors"]["lambda"]["mode"],
        soc=run.get("soc"),
        sur=run.get("sur"),
        hierarchy="mh",
        hyper=tuple(run["hyper"]),
        mh_seed=20261021,
    )
    return run, model.fit(var_data(run["dataset"]), seed=20261021)


