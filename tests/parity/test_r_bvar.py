def reference_design(dataset: str, lags: int) -> tuple[np.ndarray, np.ndarray]:
    values = raw_frame(dataset).to_numpy()
    rows = np.arange(lags, values.shape[0])
    X = np.hstack([np.ones((rows.size, 1))] + [values[rows - lag] for lag in range(1, lags + 1)])
    return values[rows], X


def reference_niw_log_ml(Y, X, B0, omega, psi) -> float:
    N, n = Y.shape
    d = n + 2.0
    w = 1.0 / np.sqrt(omega)
    Xa = np.vstack([X, np.diag(w)])
    Ya = np.vstack([Y, w[:, None] * B0])
    Q, R = np.linalg.qr(Xa)
    B = solve_triangular(R, Q.T @ Ya)
    E = Ya - Xa @ B
    S = np.diag(psi) + E.T @ E
    j = np.arange(n)
    return float(
        -N * n / 2 * np.log(np.pi)
        + np.sum(gammaln((N + d - j) / 2) - gammaln((d - j) / 2))
        - n / 2 * (np.sum(np.log(omega)) + 2 * np.sum(np.log(np.abs(np.diag(R)))))
        + d / 2 * np.sum(np.log(psi))
        - (N + d) / 2 * np.linalg.slogdet(S)[1]
    )


def reference_log_ml(case: dict[str, Any], entry: dict[str, Any]) -> float:
    Y, X = reference_design(case["dataset"], case["lags"])
    n, p = Y.shape[1], case["lags"]
    psi = np.asarray(case["psi"])
    omega = np.concatenate(
        [[case["var_const"]]]
        + [entry["lambda"] ** 2 / lag ** case["alpha"] / psi for lag in range(1, p + 1)]
    )
    B0 = np.zeros((1 + n * p, n))
    B0[1 : n + 1] = case["mean"] * np.eye(n)
    if entry.get("ybar0") is None:
        return reference_niw_log_ml(Y, X, B0, omega, psi)
    y0 = np.asarray(case["ybar0"][entry["ybar0"]])
    Yd, Xd = [], []
    if entry.get("soc") is not None:
        Ys = np.diag(y0) / entry["soc"]
        Yd.append(Ys)
        Xd.append(np.hstack([np.zeros((n, 1))] + [Ys] * p))
    if entry.get("sur") is not None:
        ys = y0[None, :] / entry["sur"]
        Yd.append(ys)
        Xd.append(np.hstack([[[1.0 / entry["sur"]]]] + [ys] * p))
    Yd, Xd = np.vstack(Yd), np.vstack(Xd)
    full = reference_niw_log_ml(np.vstack([Yd, Y]), np.vstack([Xd, X]), B0, omega, psi)
    return full - reference_niw_log_ml(Yd, Xd, B0, omega, psi)


def test_fixture_metadata_and_data_hashes():
    for name in ("r_bvar_logml.json", "r_bvar_posterior.json", "r_bvar_eb.json", "r_bvar_mh.json"):
        meta = load(name)["meta"]
