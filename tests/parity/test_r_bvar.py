@pytest.mark.parametrize("case_id", [c["id"] for c in posterior_cases()])
def test_one_step_forecast_matches_student_t(rb, case_id):
    """At h = 1 the conjugate predictive is multivariate t: an exact check of both the R
    simulation (fixture integrity) and ours, from the fixture's NIW posterior."""
    from scipy import stats

    case = case_by_id("r_bvar_posterior.json", case_id)
    ref = case["forecast"]
    entry = next(
        g
        for g in case["grid"]
        if all(g.get(k) == ref.get(k) for k in ("lambda", "soc", "sur", "ybar0"))
    )
    B, S, Om = (np.asarray(entry[k]) for k in ("mean", "scale", "omega"))
    values, p = raw_frame(case["dataset"]).to_numpy(), case["lags"]
    n = values.shape[1]
    x = np.concatenate([[1.0], *(values[-lag] for lag in range(1, p + 1))])
    nu = entry["df"] - n + 1
    scale = np.sqrt(np.diag(S) * (1.0 + x @ Om @ x) / nu)
    probs = list(ref["probs"])
    exact = stats.t.ppf(np.asarray(probs)[:, None], nu, loc=B.T @ x, scale=scale)  # (Q, n)
    ref_q, ref_mcse = np.asarray(ref["q"])[:, 0, :], np.asarray(ref["mcse"])[:, 0, :]
    assert np.all(np.abs(ref_q - exact) <= MC_Z * ref_mcse), "R fixture vs exact predictive"
    fit = fixed_fit("r_bvar_posterior.json", case_id, ref["lambda"], ref["soc"], ref["sur"])
    result = fit.forecast(1, draws=IID_FORECAST_DRAWS, seed=17)
    paths = result.paths.transpose("chain", "draw", "horizon", "variable").to_numpy()
    paths = paths.reshape(-1, n)
    for j in range(n):
        mcse = quantile_mcse(paths[:, j], probs)
        ours = np.quantile(paths[:, j], probs)
        assert np.all(np.abs(ours - exact[:, j]) <= MC_Z * mcse), (j, ours, exact[:, j], mcse)


def _compare_forecasts(fit, ref: dict[str, Any], draws: int, seed: int) -> None:
    probs = list(ref["probs"])
    result = fit.forecast(ref["horizon"], draws=draws, seed=seed)
    ours = result.quantiles(probs).transpose("quantile", "horizon", "variable").to_numpy()
    paths = result.paths.transpose("chain", "draw", "horizon", "variable").to_numpy()
    paths = paths.reshape(-1, *paths.shape[2:])
    ref_q, ref_mcse = np.asarray(ref["q"]), np.asarray(ref["mcse"])
    assert list(result.variables) == list(ref["variables"])
    for h in range(ref["horizon"]):
        for j, variable in enumerate(ref["variables"]):
            mcse = quantile_mcse(paths[:, h, j], probs)
            assert_mc_close(
                ours[:, h, j],
                mcse,
                {"q": ref_q[:, h, j], "mcse": ref_mcse[:, h, j]},
                f"forecast h={h + 1} {variable}",
            )


