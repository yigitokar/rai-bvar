@cache
def load(name: str) -> dict[str, Any]:
    return json.loads((FIXTURES / name).read_text())


def logml_cases() -> list[dict[str, Any]]:
    return load("r_bvar_logml.json")["cases"]


def case_by_id(name: str, case_id: str) -> dict[str, Any]:
    return next(c for c in load(name)["cases"] if c["id"] == case_id)


@cache
def raw_frame(dataset: str) -> pd.DataFrame:
    meta = load("r_bvar_logml.json")["datasets"][dataset]
    frame = pd.read_csv(FIXTURES / meta["file"], index_col="date")
    frame.index = pd.PeriodIndex(frame.index, freq="Q")
    return frame.astype(np.float64)


@cache
def var_data(dataset: str):
    import rai_bvar as rb

    return rb.VARData.from_frame(raw_frame(dataset), tcodes=1)


def dummies_label(entry: dict[str, Any]) -> str:
    parts = [name for name in ("soc", "sur") if entry.get(name) is not None]
    return "+".join(parts) if parts else "none"


def entry_id(case: dict[str, Any], entry: dict[str, Any]) -> str:
    ybar0 = f"-{entry['ybar0']}" if entry.get("ybar0") else ""
    return f"{case['id']}-lam{entry['lambda']:g}-{dummies_label(entry)}{ybar0}"


def glp_entries(cases: list[dict[str, Any]]) -> list[tuple[str, int]]:
    """``(case id, grid index)`` for entries that use the GLP ȳ0 (or no dummies)."""
    return [
        (case["id"], i)
        for case in cases
        for i, entry in enumerate(case["grid"])
        if entry.get("ybar0") in (None, "glp")
    ]


def find_twin(case: dict[str, Any], entry: dict[str, Any], ybar0: str) -> dict[str, Any] | None:
    for other in case["grid"]:
        if other.get("ybar0") == ybar0 and all(
            other.get(k) == entry.get(k) for k in ("lambda", "soc", "sur")
        ):
            return other
    return None


def rel(a: float, b: float) -> float:
    return abs(a - b) / max(abs(b), 1e-300)


def scaled_max_diff(a: np.ndarray, b: np.ndarray) -> float:
    a, b = np.asarray(a, dtype=np.float64), np.asarray(b, dtype=np.float64)
    return float(np.max(np.abs(a - b)) / np.max(np.abs(b)))


def quantile_mcse(x: np.ndarray, probs: list[float], n_batches: int = 100) -> np.ndarray:
    """MCSE of quantiles of ``x`` (in sampling order; robust to autocorrelation).

    The larger of two estimates, as in ``tools/make_r_fixtures.R``: the spread of batch
    quantiles, and the delta method (sparsity ``dQ/dp`` by a ±0.01 central difference times the
    batch-means standard error of the indicator ``1{x ≤ q_p}``).
    """
    x = np.asarray(x, dtype=np.float64)
    probs_arr = np.asarray(probs, dtype=np.float64)
    size = x.size // n_batches
    batches = x[: size * n_batches].reshape(n_batches, size)
    mcse_batch = np.quantile(batches, probs_arr, axis=1).std(axis=1, ddof=1) / np.sqrt(n_batches)
    q = np.quantile(x, probs_arr)
    hi, lo = np.minimum(probs_arr + 0.01, 1.0), np.maximum(probs_arr - 0.01, 0.0)
    sparsity = (np.quantile(x, hi) - np.quantile(x, lo)) / (hi - lo)
    indicator_means = (batches[:, :, None] <= q[None, None, :]).mean(axis=1)  # (batch, prob)
    mcse_delta = sparsity * indicator_means.std(axis=0, ddof=1) / np.sqrt(n_batches)
    return np.maximum(mcse_batch, mcse_delta)


def assert_mc_close(
    ours: np.ndarray, mcse_ours: np.ndarray, ref: dict[str, Any], what: str
) -> None:
    ref_q, ref_mcse = np.asarray(ref["q"]), np.asarray(ref["mcse"])
    tol = MC_Z * np.sqrt(ref_mcse**2 + np.asarray(mcse_ours) ** 2)
    bad = np.abs(np.asarray(ours) - ref_q) > tol
    assert not bad.any(), (
        f"{what}: quantiles {np.round(ours, 6)} vs R {np.round(ref_q, 6)} "
        f"(tolerance {np.round(tol, 6)}; R MCSE {np.round(ref_mcse, 6)}, ours {np.round(mcse_ours, 6)})"
    )


