# (c) empirical Bayes: posterior mode of the hyperparameters
# ------------------------------------------------------------------------------------------------


def eb_runs() -> list[dict[str, Any]]:
    return [r for r in load("r_bvar_eb.json")["runs"] if r.get("ybar0") in (None, "glp")]


@pytest.mark.parametrize("run_id", [r["id"] for r in eb_runs()])
def test_eb_posterior_mode(rb, run_id):
    run, fit = eb_fit(run_id)
    mode = {k: float(v) for k, v in run["mode"].items()}
    for name, value in mode.items():
        assert rel(float(fit.hyper[name]), value) < RTOL_MODE, (name, fit.hyper[name], value)
    # The value at our mode cannot exceed the maximum and must be close to it.
    ours = fit.log_posterior()
    assert ours <= run["log_posterior"] + 1e-7
    assert ours >= run["log_posterior"] - 1e-4
    # Deterministic evaluation at R's mode.
    assert rel(fit.log_posterior(hyper=mode), run["log_posterior"]) < RTOL_LOG_ML
    assert rel(fit.log_ml(hyper=mode), run["log_ml"]) < RTOL_LOG_ML


