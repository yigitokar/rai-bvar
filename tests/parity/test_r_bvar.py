@pytest.mark.parametrize(
    ("case_id", "index"),
    glp_entries(logml_cases()),
    ids=[
        entry_id(case_by_id("r_bvar_logml.json", c), case_by_id("r_bvar_logml.json", c)["grid"][i])
        for c, i in glp_entries(logml_cases())
    ],
)
def test_log_ml_fixed_hyperparameters(rb, case_id, index):
    case = case_by_id("r_bvar_logml.json", case_id)
    entry = case["grid"][index]
    fit = fixed_fit("r_bvar_logml.json", case_id, entry["lambda"], entry["soc"], entry["sur"])
    np.testing.assert_allclose(fit.psi, case["psi"], rtol=1e-15)
    value = fit.log_ml()
    if rel(value, entry["log_ml"]) > RTOL_LOG_ML:
        hints = []
        twin = find_twin(case, entry, "bvar")
        if twin is not None and rel(value, twin["log_ml"]) < RTOL_LOG_ML:
            hints.append("matches BVAR's ȳ0 convention (raw rows p+1..2p), not GLP's (rows 1..p)")
        if not entry["bvar_is_exact"] and rel(value, entry["log_ml_bvar"]) < RTOL_LOG_ML:
            hints.append("matches BVAR's inexact dummy-only term (prior mean plugged in)")
        pytest.fail(
            f"log ML {value!r} vs exact {entry['log_ml']!r} (BVAR {entry['log_ml_bvar']!r}); "
            f"rel diff {rel(value, entry['log_ml']):.2e}. {'; '.join(hints)}"
        )
    if entry["bvar_is_exact"]:
        assert rel(value, entry["log_ml_bvar"]) < RTOL_LOG_ML


@pytest.mark.parametrize("case_id", ["qd_p4_rw", "sim_p4_zero"])
def test_log_ml_hyper_override(rb, case_id):
    """``fit.log_ml(hyper=...)`` re-evaluates at other hyperparameters without refitting."""
    case = case_by_id("r_bvar_logml.json", case_id)
    fit = fixed_fit("r_bvar_logml.json", case_id, 0.2, 1.0, 1.0)
    for entry in case["grid"]:
        if entry.get("soc") is None or entry.get("sur") is None or entry.get("ybar0") != "glp":
            continue
        value = fit.log_ml(hyper={"lambda": entry["lambda"]})
        assert rel(value, entry["log_ml"]) < RTOL_LOG_ML, entry_id(case, entry)


@pytest.mark.parametrize("case_id", ["qd_p4_rw", "sim_p4_rw"])
def test_log_posterior_adds_glp_hyperpriors(rb, case_id):
    """``log_posterior − log_ml`` is the sum of natural-scale Gamma log densities, as in BVAR."""
    case = case_by_id("r_bvar_logml.json", case_id)
    model = build_model(
        case, lambda_=0.2, soc=1.0, sur=1.0, hierarchy="eb", hyper=("lambda", "soc", "sur")
    )
    fit = model.fit(var_data(case["dataset"]))
    for entry in case["grid"]:
        if entry.get("soc") is None or entry.get("sur") is None or entry.get("ybar0") != "glp":
            continue
        hyper = {"lambda": entry["lambda"], "soc": entry["soc"], "sur": entry["sur"]}
        log_post, log_ml = fit.log_posterior(hyper=hyper), fit.log_ml(hyper=hyper)
        expected = sum(entry["log_hyperprior"][k] for k in ("lambda", "soc", "sur"))
        assert log_post - log_ml == pytest.approx(expected, abs=1e-9), entry_id(case, entry)
        assert rel(log_post, entry["log_posterior_bvar"]) < RTOL_LOG_ML, entry_id(case, entry)


@pytest.mark.parametrize("dataset", ["qd", "sim"])
def test_auto_psi_is_an_ar_residual_variance(rb, dataset):
    """``psi="ar"`` returns variance units (BVAR's auto ψ is a standard deviation; not used)."""
    case = next(c for c in logml_cases() if c["dataset"] == dataset)
    fit = build_model(case, lambda_=0.2, soc=None, sur=None, psi="ar").fit(var_data(dataset))
    values = load("r_bvar_logml.json")["psi_conventions"]["values"][dataset]
    variances = {k: v for k, v in values.items() if k != "bvar_auto_sd"}
