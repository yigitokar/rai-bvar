# (d) Metropolis-Hastings: posterior quantiles of hyperparameters, coefficients and forecasts
# ------------------------------------------------------------------------------------------------


def mh_runs() -> list[dict[str, Any]]:
    return load("r_bvar_mh.json")["runs"]


@pytest.mark.parametrize("run_id", [r["id"] for r in mh_runs()])
def test_mh_hyperparameter_quantiles(rb, run_id):
    run, fit = mh_fit(run_id)
    assert fit.mh is not None
    probs = list(run["probs"])
    for name, ref in run["hyper_quantiles"].items():
        draws = np.asarray(fit.mh.draws[name])
        ours = np.quantile(draws, probs)
        assert_mc_close(ours, quantile_mcse(draws, probs), ref, f"{run_id} {name}")


@pytest.mark.parametrize("run_id", [r["id"] for r in mh_runs()])
def test_mh_coefficient_and_sigma_quantiles(rb, run_id):
    run, fit = mh_fit(run_id)
    probs = list(run["probs"])
    coefs, chol = fit.draw_parameters(MH_SAMPLES, np.random.default_rng(5))
    sigma = np.einsum("sij,skj->sik", chol, chol)
    for ref in run["coefficients"]:
        x = coefs[:, ref["row"], ref["col"]]
        assert_mc_close(np.quantile(x, probs), quantile_mcse(x, probs), ref, ref["name"])
    for ref in run["sigma"]:
        x = sigma[:, ref["row"], ref["col"]]
        what = f"Sigma[{ref['row']}, {ref['col']}]"
        assert_mc_close(np.quantile(x, probs), quantile_mcse(x, probs), ref, what)


